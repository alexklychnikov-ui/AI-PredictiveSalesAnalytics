def factor_help(code: str) -> str:
    return FACTOR_HELP.get(
        code,
        "Дополнительный показатель из ваших данных. "
        "Ползунок задаёт значение в сценарии; по умолчанию — последнее из истории.",
    )


def show_glossary(st_module) -> None:
    with st_module.expander("Словарь для новичка", expanded=False):
        for title, text in GLOSSARY_SHORT:
            st_module.markdown(f"**{title}** — {text}")


def show_factor_guide(st_module, *, codes: list[str] | None = None) -> None:
    """Развёрнутые пояснения к факторам (видно без наведения на «?»)."""
    items = codes or [
        "discount_pct",
        "promo_flag",
        "marketing_spend",
        "unit_price",
        "stockout_flag",
    ]
    with st_module.expander("Что значат факторы на этой странице", expanded=True):
        st_module.markdown(
            "Ползунки отвечают на вопрос «что если изменим …». "
            "Старт каждого ползунка — последнее значение из истории (= «как сейчас»)."
        )
        for code in items:
            title = FACTOR_BLURB.get(code) or code
            st_module.markdown(f"**{title}** (`{code}`)\n\n{factor_help(code)}")


def show_page_intro(st_module, page_key: str) -> None:
    text = PAGE_INTROS.get(page_key)
    if not text:
        return
    st_module.caption(text)
    show_glossary(st_module)
